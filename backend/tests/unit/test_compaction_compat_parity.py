"""Parity guard for `adk.compaction_compat` (ADK 2 upgrade sub-doc 04).

ADK 2.x removed `_pending_function_call_ids` and
`_truncate_events_before_pending_function_call`; we now own ports of the
1.39.1 originals. This pins the ports to what the originals returned on a
fixture session with answered, unanswered, id-less and orphan-response calls.

The expected output lives in a GOLDEN file generated by the real 1.39.1
helpers, so the guard keeps working on 2.x where they no longer exist. On any
venv where the originals still import (1.31.1, 1.39.1) they are checked
against the golden too — a drift between ADK and the golden fails here, not
in the second pass.

Regenerating the golden (only ever on the 1.39.1 venv):

    COMPACTION_GOLDEN_REGENERATE=1 .venv-adk1391/bin/python -m pytest \\
        tests/unit/test_compaction_compat_parity.py

Also checks that every helper `compaction_compat` RE-EXPORTS still resolves
and runs on the installed ADK — the import is deferred, so without this a
removal would surface on the first admin replay or second pass — and that no
module in `adk/` or `admin/` imports the private helpers around the shim.
"""

from __future__ import annotations

import json
import os
from pathlib import Path

import pytest
from google.adk.events.event import Event
from google.adk.events.event_actions import EventActions, EventCompaction
from google.genai import types

from adk.compaction_compat import (
    events_to_compact_for_token_threshold,
    latest_compaction_event,
    pending_function_call_ids,
    truncate_events_before_pending_function_call,
    valid_compactions,
)

pytestmark = pytest.mark.adk_contract

GOLDEN = Path(__file__).parent / "golden" / "compaction_compat_parity.json"
GOLDEN_SOURCE_VERSION = "1.39.1"
_REGENERATE = os.environ.get("COMPACTION_GOLDEN_REGENERATE") == "1"


def _text(author: str, text: str) -> Event:
    return Event(author=author, content=types.Content(role=author, parts=[types.Part(text=text)]))


def _calls(*ids: str | None) -> Event:
    parts = [types.Part(function_call=types.FunctionCall(name=f"tool_{i}", id=i, args={})) for i in ids]
    return Event(author="model", content=types.Content(role="model", parts=parts))


def _responses(*ids: str) -> Event:
    parts = [
        types.Part(function_response=types.FunctionResponse(name=f"tool_{i}", id=i, response={"ok": True})) for i in ids
    ]
    return Event(author="user", content=types.Content(role="user", parts=parts))


def _fixture() -> list[Event]:
    """One session covering every branch of the two helpers."""
    return [
        _text("user", "hi"),  # 0
        _calls("c1"),  # 1  answered at 2
        _responses("c1"),  # 2
        _calls("c2", "c3"),  # 3  two calls in one event; c3 answered late
        _responses("c2"),  # 4
        _calls(None),  # 5  id-less call: never counted as pending
        _text("model", "thinking out loud"),  # 6
        _calls("c4"),  # 7  NEVER answered
        _text("user", "still there?"),  # 8
        _responses("c3"),  # 9  answers c3 after the pending call
        _responses("ghost"),  # 10 response with no call
        _calls("c5"),  # 11 NEVER answered
    ]


def _indices(inputs: list[Event], outputs: list[Event]) -> list[int]:
    return [next(i for i, e in enumerate(inputs) if e is out) for out in outputs]


def _cases(pending, truncate) -> dict:
    """Run a helper pair over the fixture; ids sorted, events as input indices."""
    events = _fixture()
    full_pending = pending(events)
    span = events[2:9]  # the shape the second pass truncates: a mid-session slice
    truncations = {
        "full_session_full_pending": (events, full_pending),
        "no_pending_ids": (events, set()),
        "only_foreign_ids": (events, {"ghost", "not-in-session"}),
        "late_answered_id": (events, {"c3"}),
        "mid_span_full_pending": (span, full_pending),
        "empty_events": ([], {"c4"}),
    }
    return {
        "pending_ids": {
            "full_session": sorted(full_pending),
            "prefix_before_c3_answer": sorted(pending(events[:5])),
            "empty": sorted(pending([])),
        },
        "truncate": {name: _indices(inp, truncate(inp, ids)) for name, (inp, ids) in truncations.items()},
    }


def _originals():
    """The ADK originals, or None where they are gone (2.x)."""
    try:
        from google.adk.apps.compaction import (
            _pending_function_call_ids,
            _truncate_events_before_pending_function_call,
        )
    except ImportError:
        return None
    return _pending_function_call_ids, _truncate_events_before_pending_function_call


def _adk_version() -> str:
    from google.adk import version

    return version.__version__


def _golden() -> dict:
    return json.loads(GOLDEN.read_text())


def test_regenerate_golden_from_the_real_originals():
    """Writes the golden. Runs ONLY when asked, and only on 1.39.1."""
    if not _REGENERATE:
        pytest.skip("set COMPACTION_GOLDEN_REGENERATE=1 on the 1.39.1 venv to regenerate")
    originals = _originals()
    assert originals is not None and _adk_version() == GOLDEN_SOURCE_VERSION, (
        f"the golden must come from the real {GOLDEN_SOURCE_VERSION} helpers; this venv has {_adk_version()}"
    )
    GOLDEN.parent.mkdir(parents=True, exist_ok=True)
    payload = {
        "_note": "Generated by test_compaction_compat_parity.py from the real ADK originals. Do not hand-edit.",
        "generated_with": {"google_adk": _adk_version()},
        "cases": _cases(*originals),
    }
    GOLDEN.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n")


def test_golden_came_from_the_pinned_originals():
    assert _golden()["generated_with"]["google_adk"] == GOLDEN_SOURCE_VERSION


def test_ported_helpers_match_the_golden():
    assert _cases(pending_function_call_ids, truncate_events_before_pending_function_call) == _golden()["cases"]


def test_fixture_exercises_a_pending_call():
    """Guards the guard: a fixture with nothing pending would pass vacuously."""
    cases = _golden()["cases"]
    assert cases["pending_ids"]["full_session"]
    assert cases["truncate"]["full_session_full_pending"] != list(range(len(_fixture())))


def test_originals_still_match_the_golden_where_installed():
    originals = _originals()
    if originals is None:
        pytest.skip(f"ADK {_adk_version()} no longer ships the originals — the golden stands in for them")
    assert _cases(*originals) == _golden()["cases"]


def test_no_private_compaction_import_bypasses_the_shim():
    """`compaction_compat` is only the one file to touch on a bump if nothing
    else reaches into `google.adk.apps.compaction`."""
    backend = Path(__file__).resolve().parents[2]
    shim = backend / "adk" / "compaction_compat.py"
    offenders = [
        f"{path.relative_to(backend)}:{lineno}"
        for package in ("adk", "admin")
        for path in sorted((backend / package).rglob("*.py"))
        if path != shim
        for lineno, line in enumerate(path.read_text().splitlines(), start=1)
        if "google.adk.apps.compaction import" in line or line.strip().startswith("import google.adk.apps.compaction")
    ]
    assert offenders == [], f"route these through adk.compaction_compat: {offenders}"


def test_reexported_helpers_still_resolve_on_this_adk():
    def _compaction(start: float, end: float) -> Event:
        e = Event(
            author="user",
            actions=EventActions(
                compaction=EventCompaction(
                    start_timestamp=start,
                    end_timestamp=end,
                    compacted_content=types.Content(role="model", parts=[types.Part(text="summary")]),
                )
            ),
        )
        e.timestamp = end
        return e

    events = []
    for i, ts in enumerate([1.0, 2.0, 3.0, 4.0]):
        e = _text("user", f"turn {i}")
        e.timestamp = ts
        events.append(e)
    events.insert(2, _compaction(1.0, 2.0))

    assert [(i, s, e) for i, s, e, _ in valid_compactions(events)] == [(2, 1.0, 2.0)]
    assert latest_compaction_event(events) is events[2]
    selected = events_to_compact_for_token_threshold(events=events, event_retention_size=1)
    # Seed summary first, then the raw turn past the compacted span; the last
    # turn is retained.
    assert [e.timestamp for e in selected] == [1.0, 3.0]
